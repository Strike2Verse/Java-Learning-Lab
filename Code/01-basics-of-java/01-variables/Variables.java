public class Variables {
    public static void main(String[] args) {
        String label = "XYZ"; // Stores text in a variable named label.
        int quantity = 10; // Stores a whole number in quantity.

        quantity = 15; // Changes the value already stored in quantity.

        System.out.println("Label: " + label); // Prints the text variable.
        System.out.println("Quantity: " + quantity); // Prints the updated number.
    }
}
