public class Operators {
    public static void main(String[] args) {
        int firstNumber = 20; // Stores the first whole number.
        int secondNumber = 6; // Stores the second whole number.

        System.out.println("Sum: " + (firstNumber + secondNumber)); // Adds the values.
        System.out.println("Difference: " + (firstNumber - secondNumber)); // Subtracts values.
        System.out.println("Product: " + (firstNumber * secondNumber)); // Multiplies values.
        System.out.println("Quotient: " + (firstNumber / secondNumber)); // Divides as whole numbers.
        System.out.println("Remainder: " + (firstNumber % secondNumber)); // Finds what is left.
        System.out.println("First is greater: " + (firstNumber > secondNumber)); // Compares values.
    }
}
