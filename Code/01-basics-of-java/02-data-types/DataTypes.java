public class DataTypes {
    public static void main(String[] args) {
        String title = "XYZ"; // String stores text.
        int count = 10; // int stores a whole number.
        double price = 49.99; // double stores a decimal number.
        boolean available = true; // boolean stores true or false.
        char code = 'P'; // char stores one character.

        System.out.println("Title: " + title); // Prints text.
        System.out.println("Count: " + count); // Prints a whole number.
        System.out.println("Price: " + price); // Prints a decimal number.
        System.out.println("Available: " + available); // Prints true or false.
        System.out.println("Code: " + code); // Prints one character.
    }
}
